"""Generate golden_bitorder.json from bitorder.dbc using cantools.

Dev-only cross-check fixture (spec §7.2 / §13.1). NOT run in CI — the Rust
test `bitorder_golden.rs` reads the committed JSON, so Python is unnecessary
after generation. Regenerate with:

    python crates/lumelog-can/tests/gen_golden.py

Requires: cantools==39.4.5  (pip install cantools==39.4.5)

The golden is the AUTHORITATIVE bit-order reference: the Rust decoder must be
adjusted to match it, never the other way around.
"""
import json
import os

import cantools

HERE = os.path.dirname(os.path.abspath(__file__))
DBC = os.path.join(HERE, "data", "bitorder.dbc")
OUT = os.path.join(HERE, "data", "golden_bitorder.json")

# Fixed 8-byte frames chosen to exercise, for BOTH byte orders: unsigned and
# signed signals (top raw bit set -> negative), a cross-byte length (20), and
# non-unit factor / non-zero offset.
FRAMES = {
    "IntelMsg": "DEADBEEF12345678",
    "MotoroMsg": "89ABCDEF01234567",
}


def main() -> None:
    db = cantools.database.load_file(DBC)
    entries = []
    for msg_name, hexdata in FRAMES.items():
        msg = db.get_message_by_name(msg_name)
        data = bytes.fromhex(hexdata)
        raw = msg.decode(data, decode_choices=False, scaling=False)
        phys = msg.decode(data, decode_choices=False, scaling=True)
        for sig_name in sorted(raw):
            entries.append(
                {
                    "message": msg_name,
                    "signal": sig_name,
                    "frame_hex": hexdata,
                    "raw": int(raw[sig_name]),
                    "physical": float(phys[sig_name]),
                }
            )
    payload = {
        "cantools_version": cantools.__version__,
        "note": "authoritative bit-order golden; generated by gen_golden.py",
        "entries": entries,
    }
    with open(OUT, "w", encoding="utf-8") as f:
        json.dump(payload, f, indent=2, sort_keys=True)
    print(f"wrote {len(entries)} entries (cantools {cantools.__version__}) -> {OUT}")


if __name__ == "__main__":
    main()
